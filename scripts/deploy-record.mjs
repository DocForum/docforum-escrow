#!/usr/bin/env node
// Writes one scripts/deploy record (issue #89) to:
//   - deployments.json (machine-readable, newest last)
//   - sdk/src/deployments.generated.ts (the same data, bundled into the SDK
//     so it works in Node, Deno, Bun and browsers without file access)
//   - docs/testnet-deployments.md (human-readable, newest first)
//
// Usage: node scripts/deploy-record.mjs <record.json>
//        node scripts/deploy-record.mjs --sync   (regenerate the SDK module
//                                                  from deployments.json only)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = path.join(root, "deployments.json");
const sdkPath = path.join(root, "sdk/src/deployments.generated.ts");
const docsPath = path.join(root, "docs/testnet-deployments.md");
export const DOCS_MARKER = "<!-- scripts/deploy inserts new records below this line -->";

const SUPPORTED = new Set(["testnet", "local"]);

function loadDeployments() {
  if (!existsSync(jsonPath)) return { version: 1, deployments: [] };
  const doc = JSON.parse(readFileSync(jsonPath, "utf8"));
  if (doc.version !== 1 || !Array.isArray(doc.deployments)) {
    throw new Error("deployments.json must be { version: 1, deployments: [...] }");
  }
  return doc;
}

export function renderSdkModule(doc) {
  return `// GENERATED by scripts/deploy-record.mjs from /deployments.json. Do not edit.
// Regenerate with: node scripts/deploy-record.mjs --sync
import type { DeploymentsDocument } from "./deployments.js";

/** Known contract deployments bundled with the SDK (issue #89); see \`deployments.ts\`. */
export const KNOWN_DEPLOYMENTS: DeploymentsDocument = ${JSON.stringify(doc, null, 2)};
`;
}

export function renderDocsSection(r) {
  const short = r.gitSha.slice(0, 7);
  const tx = (h) => (h ? (r.explorer ? `${r.explorer.tx}${h}` : `\`${h}\``) : "n/a");
  const rows = [
    `| Network | ${r.network} (\`${r.networkPassphrase}\`) |`,
    `| Contract ID | \`${r.contractId}\` |`,
    ...(r.explorer ? [`| Explorer | ${r.explorer.contract} |`] : []),
    `| WASM hash | \`${r.wasmHash}\` |`,
    `| WASM upload tx | ${r.uploadTxHash ? tx(r.uploadTxHash) : "none (WASM was already on the network)"} |`,
    `| Deploy tx | ${tx(r.deployTxHash)} |`,
    `| Source commit | \`${short}\` (\`${r.gitSha}\`) |`,
    `| Constructor \`allowed_tokens\` | ${r.allowedTokens.length ? r.allowedTokens.map((t) => `\`${t}\``).join(", ") : "empty (any token)"} |`,
  ];
  const cases = r.verification.map((v) => {
    const where = v.txHash ? `[transaction](${tx(v.txHash)})` : "rejected in simulation, not submitted";
    const id = v.escrowId === null ? "" : ` escrow ${v.escrowId}`;
    return `- \`${v.case}\`${id}: ${v.result}, expected ${v.expected}; ${where}.`;
  });
  return [
    `## \`docforum_escrow\` — ${r.deployedAt.slice(0, 10)} (\`${short}\`, recorded by \`scripts/deploy\`)`,
    "",
    "| | |",
    "|---|---|",
    ...rows,
    "",
    "### Scripted live verification",
    "",
    "The on-chain WASM was fetched after deployment and matched the hash above.",
    "",
    ...cases,
    "",
  ].join("\n");
}

function insertDocs(section) {
  const docs = readFileSync(docsPath, "utf8");
  const at = docs.indexOf(DOCS_MARKER);
  if (at === -1) throw new Error(`marker not found in ${docsPath}`);
  const end = at + DOCS_MARKER.length;
  writeFileSync(docsPath, `${docs.slice(0, end)}\n\n${section}${docs.slice(end).replace(/^\n+/, "\n")}`);
}

function main() {
  const arg = process.argv[2];
  if (!arg) {
    console.error("Usage: node scripts/deploy-record.mjs <record.json> | --sync");
    process.exit(2);
  }
  const doc = loadDeployments();
  if (arg !== "--sync") {
    const record = JSON.parse(readFileSync(arg, "utf8"));
    if (!SUPPORTED.has(record.network)) {
      throw new Error(`refusing to record network "${record.network}"`);
    }
    if (record.network === "local") {
      throw new Error("local (dry-run) deployments are never recorded");
    }
    doc.deployments.push(record);
    writeFileSync(jsonPath, `${JSON.stringify(doc, null, 2)}\n`);
    insertDocs(renderDocsSection(record));
  }
  writeFileSync(sdkPath, renderSdkModule(doc));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
